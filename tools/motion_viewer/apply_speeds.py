"""Apply the motion speeds the user adopted in the motion viewer to the game.

The viewer's adopt button writes one document per sheet row to the artifact database collection
`motion_speeds` (user 2026-10-15: "모션 별 시간은 모션 뷰어에서 직접 조절 후 채택 버튼을 눌러 기록").
The lead exports that collection (ArtifactData `list`, one JSON file per document) and runs:

    python tools/motion_viewer/apply_speeds.py <export folder or records .json>

It writes
  - art/motion_speeds.json: every record, sorted (the copy the repo keeps), and
  - smash-nine-prototype/characters/common/MotionSpeeds.gd: "<prefix>/<body|default>/<row>" -> fps,
    which the game's sheet loader plays each row at (PlayerBase._add_sheet_animations).
and prints what changed against the previous MotionSpeeds.gd.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
RECORDS_OUT = ROOT / "art" / "motion_speeds.json"
SCRIPT_OUT = ROOT / "smash-nine-prototype" / "characters" / "common" / "MotionSpeeds.gd"
FIELDS = ("character", "body", "sheet", "row", "frames", "table_fps", "factor", "fps", "adopted_at", "viewer_commit")

HEADER = '''extends RefCounted
## Motion speeds the user adopted in the motion viewer (user 2026-10-15: "모션 별 시간은 모션 뷰어에서
## 직접 조절 후 채택 버튼을 눌러 기록하여 데이터를 남기는 식"). Generated by
## tools/motion_viewer/apply_speeds.py from the viewer's `motion_speeds` records (the repo's copy is
## art/motion_speeds.json): adopt again in the viewer and rerun the tool, do not edit by hand.
## Key "<sheet prefix>/<body or default>/<row>" -> the fps the game plays that row at. A row without a
## key plays at its table fps, the speed it was drawn for. Rows played by the pose clock keep their
## hit timing; the clock shows no drawing after the strike for less than one frame of this speed
## (PlayerBase._sprite_pose_timeline).

'''

FOOTER = '''
## The fps of one row of a fighter's sheet: the body's own record, then the single-body one. With no
## body (tests, the dummy) the order the sheet loader picks a file in: unsuffixed, male, female.
static func fps(prefix: String, body: String, row: String, table_fps: float) -> float:
	var bodies: Array = [body, "default"] if body != "" else ["default", "male", "female"]
	for key_body in bodies:
		var key := "%s/%s/%s" % [prefix, key_body, row]
		if FPS.has(key):
			return float(FPS[key])
	return table_fps
'''


def load_records(source: Path) -> list[dict]:
    if source.is_dir():
        docs = [json.loads(path.read_text(encoding="utf-8")) for path in sorted(source.glob("*.json"))]
    else:
        data = json.loads(source.read_text(encoding="utf-8"))
        docs = data["records"] if isinstance(data, dict) else data
    records = []
    for doc in docs:
        missing = [field for field in ("character", "row", "fps") if field not in doc]
        if missing:
            raise ValueError(f"record without {missing}: {doc}")
        records.append({field: doc.get(field, "") for field in FIELDS})
    return sorted(records, key=key_of)


def key_of(record: dict) -> str:
    return f"{record['character']}/{record['body'] or 'default'}/{record['row']}"


def number(value) -> str:
    """A GDScript float literal: 9 -> 9.0, 11.31 -> 11.31."""
    text = f"{float(value):g}"
    return text if "." in text else text + ".0"


def previous_fps() -> dict[str, float]:
    if not SCRIPT_OUT.exists():
        return {}
    text = SCRIPT_OUT.read_text(encoding="utf-8")
    return {key: float(value) for key, value in re.findall(r'"([a-z0-9_]+/[a-z]+/[a-z0-9_]+)":\s*([0-9.]+)', text)}


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__)
        return 2
    records = load_records(Path(sys.argv[1]))
    keys = [key_of(record) for record in records]
    if len(set(keys)) != len(keys):
        raise ValueError("two records for the same row")
    before = previous_fps()
    rows = ",\n".join("  " + json.dumps(record, ensure_ascii=False) for record in records)
    RECORDS_OUT.write_text('{"collection": "motion_speeds", "records": [\n' + rows + "\n]}\n", encoding="utf-8", newline="\n")
    lines = [f'\t"{key_of(r)}": {number(r["fps"])},  # {r["table_fps"]:g} x {float(r["factor"]):.2f}' for r in records]
    SCRIPT_OUT.write_text(HEADER + "const FPS := {\n" + "\n".join(lines) + "\n}\n" + FOOTER, encoding="utf-8", newline="\n")
    after = {key_of(r): float(r["fps"]) for r in records}
    changed = [k for k in after if before.get(k) != after[k]]
    removed = [k for k in before if k not in after]
    print(f"{len(records)} rows -> {SCRIPT_OUT.relative_to(ROOT)} ({len(changed)} new or changed, {len(removed)} removed)")
    for key in changed:
        print(f"  {key}: {before.get(key, '-')} -> {after[key]:g}")
    for key in removed:
        print(f"  {key}: {before[key]:g} -> table fps")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
